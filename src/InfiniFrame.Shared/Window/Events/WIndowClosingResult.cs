/// <summary>
///     Represents the result of a window closing operation.
/// </summary>
public enum WindowClosingResult {
    /// <summary>
    ///     The window should be closed.
    /// </summary>
    Close = 0,
    /// <summary>
    ///     The window closing should be cancelled.
    /// </summary>
    Cancel = 1
}